package com.mostafa.majiddelbandam.domain

object MajidQuotes {
    private val play = listOf(
        "یه‌حرف عوض کن دلبندم، کل حیاط عوض می‌شه!",
        "آرام… کلمه با تو راه می‌آید، مثل گربهٔ پشت ارسی.",
        "این نردبان چوبی‌ست، عجله‌اش نکن که می‌شکند.",
        "حوض فیروزه شاهد است: صبر، از قران گران‌تر است.",
        "اگر گیر کردی، به شمعدانی‌ها نگاه کن؛ آن‌ها هم یک برگ عوض می‌کنند.",
        "میرزا می‌گوید فرهنگ لغت، صندوقچهٔ ناموس این خانه است.",
        "از «خانم» تا «خونه» فقط یک نفس فاصله است.",
        "حرف که درست بنشیند، فال حافظ هم لبخند می‌زند."
    )

    private val win = listOf(
        "به به! کارنامهٔ طلایی، لایق پیشانیِ باز توست.",
        "ستاره‌ها برای تو روشن شدند، نه برای طاق ارسی.",
        "مجید دلبندم از شوق، کلاه نمدی‌اش را هوا کرد!",
        "این قران‌ها را بگذار کنار حوض، مبادا زنگ بزنند.",
        "آفرین دلبندم؛ نردبان را تا عرش بالا بردی."
    )

    fun playing(seed: Int): String = play[Math.floorMod(seed, play.size)]

    fun winning(seed: Int): String = win[Math.floorMod(seed, win.size)]
}
